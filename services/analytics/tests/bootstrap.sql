CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN;
CREATE TABLE public.taskflow_ads_user_profiles(
 uid text PRIMARY KEY,
 declared_age smallint,
 age_declared_at timestamptz,
 profiling_consent boolean NOT NULL DEFAULT false
);
CREATE TABLE public.taskflow_ads_interest_scores(
 uid text NOT NULL,
 topic text NOT NULL,
 score integer NOT NULL DEFAULT 1,
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE SCHEMA cron;
CREATE TABLE cron.job(
 jobid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 jobname text UNIQUE NOT NULL,
 schedule text NOT NULL,
 command text NOT NULL
);
-- Sustituto limitado de pg_cron para comprobar SQL en PostgreSQL aislado.
-- La validación de ejecución real de pg_cron sigue pendiente en Supabase.
CREATE FUNCTION cron.schedule(p_name text,p_expression text,p_command text)
RETURNS bigint LANGUAGE plpgsql AS $function$
DECLARE v_id bigint;
BEGIN
 INSERT INTO cron.job(jobname,schedule,command)
 VALUES(p_name,p_expression,p_command)
 RETURNING jobid INTO v_id;
 RETURN v_id;
END
$function$;
